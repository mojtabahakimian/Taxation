using Prg_Moadian.FUNCTIONS;

namespace MoadianLocalTest;

/// <summary>
/// گروه ۲۷ — احکام واقعیِ سامانه، به‌عنوان تست دائمی.
///
/// این حالت‌ها از یک نصب **دیگر** (مشتری «مروارید») بیرون کشیده شده‌اند؛ نصبی که
/// این تست‌ها هرگز علیه‌اش نوشته نشده بودند. ۱۴۸ صورتحسابش را سامانهٔ واقعی رد
/// کرده و متن خطا نشان می‌دهد دقیقا چه چیزی را نپذیرفته. آن داده‌ها یک «حقیقت
/// بیرونی» هستند: نه برداشت ما از سند، نه رفتار سرور ساختگی.
///
/// یافتهٔ کلیدی: سامانه برای شماره اقتصادی خریدار، الگوی طول را **بر اساس نوع
/// شخص** می‌خواهد و این دقیقا با نگاشت MoadianRules می‌خواند:
///
///     Tob = ۱ (حقیقی)  →  سامانه الگوی ^\d{14}$ خواست
///     Tob = ۲ (حقوقی)  →  سامانه الگوی ^\d{11}$ خواست
///
/// و کد خطای ۰۰۰۱۲ («فیلد شماره اقتصادی خریدار خالی است») که تا پیش از این در
/// هیچ داده‌ای ندیده بودیم.
///
/// شناسه‌های واقعی خریداران اینجا نیامده‌اند؛ فقط *شکل* (طول و خالی‌بودن) که
/// همان چیزی است که سامانه کنترل می‌کند.
///
/// نکتهٔ مهم: این ۱۴۸ ارسال مربوط به مهر ۱۴۰۴ است، یعنی **پیش از** افزوده‌شدن
/// ValidateBuyer. پس این گروه می‌سنجد که آیا آن نگهبان، اگر آن زمان وجود داشت،
/// همین‌ها را جلوی در می‌گرفت یا نه.
/// </summary>
internal static class RealWorldRejections
{
    /// <summary>یک حکم واقعی سامانه: ورودی، و اینکه به هویت خریدار ایراد گرفت یا نه.</summary>
    private readonly record struct Verdict(
        string Label, int Inty, int Inp, int Tob,
        string Tinb, string Bid, string Bpc,
        bool BuyerWasAcceptable, int Count);

    // شماره‌های ساختگی با طول درست — هویت واقعی هیچ خریداری اینجا نیست.
    private static string Digits(int n) => new string('1', n);

    private static readonly Verdict[] Cases =
    {
        // ---------- سامانه رد کرد : ۰۰۰۱۲ «شماره اقتصادی خریدار خالی است» ----------
        new("نوع اول، حقیقی، شماره اقتصادی خالی",      1, 1, 1, "",   "",   "",   false, 45),
        new("نوع اول، حقیقی، همه فیلدها null",          1, 1, 1, "",   null, null, false,  8),
        new("نوع اول، حقوقی، شماره اقتصادی خالی",      1, 1, 2, "",   "",   "",   false, 12),
        new("نوع اول، حقوقی، همه فیلدها null",          1, 1, 2, "",   null, null, false,  1),

        // ---------- سامانه رد کرد : ۰۱۰۱۲۰۴ با الگوی ^\d{14}$ روی خریدار حقیقی ----------
        new("نوع اول، حقیقی، شماره اقتصادی ۱۱ رقمی",   1, 1, 1, Digits(11), "",   "",   false, 17),
        // ۹ فقره از ۱۰ موردِ «۱۲ کاراکتری» اصلا رقم نبودند: کاربر شمارهٔ تلفن
        // ثابت با خط تیره در فیلد شناسهٔ اقتصادی زده بود (شکل واقعی: 011-32221618).
        // شمارهٔ واقعی هیچ مشتری‌ای اینجا نیست، فقط همان شکل.
        new("نوع اول، حقیقی، شمارهٔ تلفن به‌جای شناسه",  1, 1, 1, "011-11111111", "", "", false,  9),
        new("نوع اول، حقیقی، شناسهٔ ۱۲ رقمیِ واقعا عددی", 1, 1, 1, Digits(12), "",   "",   false,  1),
        new("نوع اول، حقیقی، شماره اقتصادی ۱۳ رقمی",   1, 1, 1, Digits(13), "",   "",   false,  6),
        new("نوع اول، حقیقی، شماره اقتصادی ۱۰ رقمی",   1, 1, 1, Digits(10), "",   "",   false,  5),
        new("نوع اول، حقیقی، ۱۱ رقمی با فیلدهای null", 1, 1, 1, Digits(11), null, null, false,  2),
        new("نوع اول، حقیقی، ۱۲ کاراکتری با فیلدهای null", 1, 1, 1, Digits(12), null, null, false, 0),
        new("نوع اول، حقیقی، ۱۳ رقمی با فیلدهای null", 1, 1, 1, Digits(13), null, null, false,  1),

        // ---------- سامانه رد کرد : ۰۱۰۱۲۰۴ با الگوی ^\d{11}$ روی خریدار حقوقی ----------
        new("نوع اول، حقوقی، شماره اقتصادی ۱۰ رقمی",   1, 1, 2, Digits(10), "",   "",   false,  1),

        // ---------- سامانه از بابت خریدار ایراد نگرفت ----------
        // توجه: این صورتحساب‌ها هم رد شدند — ولی با کد ۰۲۰۰۲ (تاریخ صدور)،
        // نه به‌خاطر خریدار. پس «پذیرفته شدن» اینجا یعنی «سامانه به هویت
        // خریدار ایراد نگرفت»، نه اینکه صورتحساب ثبت شده باشد.
        // اگر نگهبان ما اینها را هم رد کند، «مثبت کاذب» داده است.
        new("نوع اول، حقیقی، شماره اقتصادی ۱۴ رقمی",   1, 1, 1, Digits(14), "",   "",   true, 13),
        new("نوع اول، حقیقی، ۱۴ رقمی با فیلدهای null", 1, 1, 1, Digits(14), null, null, true,  1),
        new("نوع اول، حقوقی، شماره اقتصادی ۱۱ رقمی",   1, 1, 2, Digits(11), "",   "",   true,  1),
        new("نوع دوم، حقیقی، همه‌چیز خالی",             2, 1, 1, "",   "",   "",   true, 20),
        new("نوع دوم، حقیقی، همه‌چیز null",             2, 1, 1, "",   null, null, true,  4),
        new("نوع دوم، حقوقی، همه‌چیز خالی",             2, 1, 2, "",   "",   "",   true,  1),
    };

    public static void Run(Action<string, bool, string> check, Action<string> line)
    {
        int n = 1;
        void C(string name, bool ok, string detail = "") => check($"۲۷-{Fa(n++)} {name}", ok, detail);

        int agree = 0, missed = 0, falseAlarm = 0, invoices = 0;

        foreach (var c in Cases)
        {
            bool weAccept = MoadianRules.ValidateBuyer(c.Inty, c.Inp, c.Tob, c.Tinb, c.Bid, c.Bpc, out var err);
            invoices += c.Count;

            if (weAccept == c.BuyerWasAcceptable) agree += c.Count;
            else if (c.BuyerWasAcceptable) falseAlarm += c.Count;   // ما رد کردیم، سامانه نه
            else missed += c.Count;                                 // سامانه رد کرد، ما نه

            C($"{c.Label} — {(c.BuyerWasAcceptable ? "سامانه به خریدار ایراد نگرفت" : "سامانه به‌خاطر خریدار رد کرد")}",
              weAccept == c.BuyerWasAcceptable,
              weAccept == c.BuyerWasAcceptable
                  ? $"{c.Count} صورتحساب، هم‌نظر"
                  : (c.BuyerWasAcceptable
                        ? $"مثبت کاذب — ما بی‌دلیل جلویش را می‌گیریم: {err}"
                        : $"از دست رفت — این {c.Count} صورتحساب بی‌هشدار می‌رفتند و رد می‌شدند"));
        }

        C("هیچ صورتحسابی که سامانه رد کرده از نگهبان رد نمی‌شود",
          missed == 0, missed == 0 ? "صفر" : $"{missed} صورتحساب");
        C("هیچ صورتحساب سالمی بی‌دلیل بلاک نمی‌شود",
          falseAlarm == 0, falseAlarm == 0 ? "صفر" : $"{falseAlarm} صورتحساب");

        line($"      · روی {invoices} صورتحسابِ واقعیِ یک نصب دیگر: {agree} هم‌نظر، " +
             $"{missed} از دست رفته، {falseAlarm} مثبت کاذب.");

        // ---------------- نگاشت طول که سامانه خودش اعلام کرد ----------------
        //
        // متن خطای سامانه عین الگو را می‌نویسد، پس این حدس نیست:
        //   Tob=۱ → ^\d{14}$   و   Tob=۲ → ^\d{11}$
        C("نگاشت طول شماره اقتصادی با آنچه سامانه در متن خطا خواست می‌خواند",
          !MoadianRules.ValidateBuyer(1, 1, 1, Digits(11), "", "", out _) &&
           MoadianRules.ValidateBuyer(1, 1, 1, Digits(14), "", "", out _) &&
          !MoadianRules.ValidateBuyer(1, 1, 2, Digits(14), "", "", out _) &&
           MoadianRules.ValidateBuyer(1, 1, 2, Digits(11), "", "", out _),
          "حقیقی ۱۴ رقم، حقوقی ۱۱ رقم");
    }

    private static string Fa(int x) =>
        string.Concat(x.ToString().Select(c => (char)('۰' + (c - '0'))));
}
